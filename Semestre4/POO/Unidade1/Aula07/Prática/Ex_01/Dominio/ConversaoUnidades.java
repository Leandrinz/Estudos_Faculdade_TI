package Semestre4.POO.Unidade1.Aula07.Prática.Ex_01.Dominio;

public class ConversaoUnidades {
    public static double polegadasParaCentimetros(double polegadas){
        return polegadas*2.54;
    }
    public static double pesParaCentimetro(double pes){
        return pes*30.48;
    }
    public static double milhasParaKilometros(double milhas){
        return milhas*1.609;
    }

}
